"""The eval runner's models (spec/schema/eval.v1.schema.json).

Its shapes reference the event schema by URN. The generator sees one schema, the event schema
with every eval def added under its own name (URN refs made local), normalized together; every
model the event schema already defines is then dropped from the output and imported from
`events_v1`, so each event type has exactly one Python class (as for the host API).
"""

import json
from pathlib import Path

from host_api_models import EVENTS_URN
from schema_normalize import Json, Obj, as_obj, normalize

SPEC = Path(__file__).resolve().parent.parent.parent / "spec" / "schema"
EVAL_SCHEMA = SPEC / "eval.v1.schema.json"
HEADER = (
    "# Generated by python/tools/regen_models.py from\n"
    "# spec/schema/eval.v1.schema.json. Do not edit by hand.\n"
    "# pyright: reportPrivateUsage=false\n"
    "# (the constrained id aliases are the event module's private names)"
)


def _local(node: Json) -> Json:
    if isinstance(node, dict):
        return {
            k: v.replace(EVENTS_URN, "#/$defs/")
            if k == "$ref" and isinstance(v, str)
            else _local(v)
            for k, v in node.items()
        }
    if isinstance(node, list):
        return [_local(v) for v in node]
    return node


def combined_eval_schema(events: Obj) -> Obj:
    evals = as_obj(as_obj(json.loads(EVAL_SCHEMA.read_text(encoding="utf-8")))["$defs"])
    defs = dict(as_obj(events["$defs"]))
    for name, shape in evals.items():
        if name in defs:
            raise SystemExit(f"regen: eval shape {name} collides with an event $def")
        defs[name] = _local(shape)
    return normalize({**events, "$defs": defs})
